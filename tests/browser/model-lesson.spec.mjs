import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('chapter starting point, main application and teaching guidance stay distinct',async({page})=>{
 await page.goto('/#loops');
 await expect(page.locator('.lesson-preparation')).toHaveCount(1);
 await expect(page.locator('.lesson-preparation').getByRole('link',{name:'Choose today’s lesson',exact:true})).toBeVisible();
 await expect(page.locator('.chapter-route-controls').getByRole('link',{name:'Choose a lesson',exact:true})).toHaveCount(0);
 await expect(page.locator('.chapter-teacher-guidance')).not.toHaveAttribute('open','');
 const taskFirst=await page.locator('.chapter-application').evaluate(el=>!!(el.compareDocumentPosition(document.querySelector('.chapter-reinforcement'))&Node.DOCUMENT_POSITION_FOLLOWING));
 expect(taskFirst).toBeTruthy();
 await page.locator('.student-journey summary').click();
 await expect(page.locator('.student-journey summary')).toContainText('Study this chapter independently');
 await page.locator('.chapter-teacher-guidance > summary').click();
 await expect(page.getByText('Pygame preparation before the project.',{exact:true})).toBeVisible();
 await page.goto('/#loops/heading-check-your-understanding');
 await expect(page.locator('#heading-check-your-understanding')).toBeInViewport();
 await page.getByRole('button',{name:'Once before the loop',exact:true}).click();
 await expect(page.locator('#chapter-feedback')).toContainText('Correct.');
 await expect(page.locator('.student-journey')).toHaveAttribute('open','');
 await page.locator('.student-journey a[href="#loops/heading-trace-the-running-total"]').first().click();
 await expect(page.locator('#chapter-feedback')).toContainText('Correct.');
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
});
test('loops retains one worked trace with its original heading, prediction and changed practice',async({page})=>{
 await page.goto('/#loops/heading-watch-the-total-grow');
 const guide=page.locator('[data-learning-guide="loops"]');
 await expect(guide.getByRole('heading',{name:'Watch the total grow',exact:true})).toBeVisible();
 await expect(guide.locator('table')).toHaveCount(0);
 const traces=await page.locator('main table').evaluateAll(tables=>tables.map(table=>[...table.querySelectorAll('tr')].slice(1).map(row=>[...row.querySelectorAll('td')].map(cell=>cell.textContent.replace(/\$/g,'').trim()))).filter(rows=>JSON.stringify(rows)===JSON.stringify([['1','5','0','5'],['2','7','5','12'],['3','3','12','15']])).length);
 expect(traces).toBe(1);
 await expect(guide.getByText('Trace donations of $2, $0 and $4 without running code.',{exact:false})).toBeVisible();
 await guide.locator('summary').click();
 const answer=guide.getByText('$3, only the last donation.',{exact:false});
 await expect(answer).toBeVisible();
 await page.evaluate(()=>{window.print=()=>window.dispatchEvent(new Event('beforeprint'));});
 await page.getByRole('button',{name:'Print student copy',exact:true}).click();
 await page.emulateMedia({media:'print'});
 await expect(answer).toBeHidden();
 await page.emulateMedia({media:'screen'});
 await page.evaluate(()=>window.dispatchEvent(new Event('afterprint')));
 await expect(answer).toBeVisible();
});
test('model lesson keeps practice, disclosed feedback and student printing distinct',async({page})=>{
 await page.goto('/lessons/?unit=1#u1-l15');
 await page.getByRole('link',{name:'Start the focused lesson:'}).click();
 await expect(page.getByRole('heading',{name:'Trace counters and accumulators',exact:true})).toBeVisible();
 await expect(page.locator('details[open]')).toHaveCount(0);
 await page.getByText('Reveal the worked trace after predicting',{exact:true}).focus();
 await page.keyboard.press('Enter');
 await expect(page.getByText('The loop runs three times and prints 12.',{exact:false})).toBeVisible();
 await page.getByRole('link',{name:'3 Practice',exact:true}).click();
 await expect(page).toHaveURL(/#practice$/);
 await expect(page.getByRole('heading',{name:'B. Independent program'})).toBeVisible();
 await page.getByRole('link',{name:'I have attempted it — compare my work'}).click();
 await page.getByText('Reveal the Activity 01 explained answers',{exact:true}).click();
 await expect(page.getByText('Rounds 1,2,3,4 add 2,4,6,8;', {exact:false})).toBeVisible();
 await page.emulateMedia({media:'print'});
 for(const answer of await page.locator('#check details').all())await expect(answer).toBeHidden();
 await expect(page.locator('.teacher')).toBeHidden();
 await expect(page.getByRole('heading',{name:'B. Independent program'})).toBeVisible();
 await page.emulateMedia({media:'screen'});
 for(const answer of await page.locator('#check details').all())await expect(answer).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 const scan=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
 expect(scan.violations).toEqual([]);
});

test('optional activity bank supports selection, separate print copies and accessible code',async({page})=>{
 await page.goto('/lessons/loops/activities/');
 await expect(page.locator('article.activity')).toHaveCount(8);
 await expect(page.locator('details[open]')).toHaveCount(0);
 await page.getByLabel('Choose an activity').selectOption('budget');
 await expect(page.locator('article.activity:visible')).toHaveCount(1);
 await expect(page.getByRole('status')).toHaveText('1 of 8 activities shown');
 await page.locator('#budget details').first().locator('summary').click();
 await page.evaluate(()=>{window.print=()=>{};});
 await page.getByRole('button',{name:'Print selected student activities',exact:true}).click();
 await page.emulateMedia({media:'print'});
 for(const answer of await page.locator('#budget details').all())await expect(answer).toBeHidden();
 await expect(page.locator('#human-trace')).toBeHidden();
 await page.evaluate(()=>window.dispatchEvent(new Event('afterprint')));
 await page.emulateMedia({media:'screen'});
 await expect(page.locator('#budget details[open]')).toHaveCount(1);
 await page.getByRole('button',{name:'Print selected activities with teacher guidance and answers',exact:true}).click();
 await page.emulateMedia({media:'print'});
 for(const answer of await page.locator('#budget details').all())await expect(answer).toBeVisible();
 await expect(page.locator('#budget details[open]')).toHaveCount(2);
 await page.evaluate(()=>window.dispatchEvent(new Event('afterprint')));
 await page.emulateMedia({media:'screen'});
 await expect(page.locator('#budget details[open]')).toHaveCount(1);
 await page.getByLabel('Choose an activity').selectOption('');
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 const scan=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
 expect(scan.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}))).toEqual([]);
});
