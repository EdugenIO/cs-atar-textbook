import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=file=>fs.readFileSync(new URL(`../${file}`,import.meta.url),'utf8');
const model=JSON.parse(read('data-quality-model.json'));
const csv=file=>read(`dist/${file}`).trim().split(/\r?\n/).slice(1).map(line=>
  [...line.matchAll(/"((?:[^"]|"")*)"/g)].map(match=>match[1].replaceAll('""','"')));
assert.deepEqual(new Set(model.factors.map(row=>row[0])),new Set(['Accuracy','Currency','Relevance','Authenticity','Outliers']));
assert.equal(model.raw.length,12);
assert.equal(new Set(model.raw.map(row=>row[0])).size,12);
assert.equal(model.decisions.length,12);
assert.deepEqual(model.decisions.map(row=>row[0]),model.raw.map(row=>row[0]),'Every raw row has a traceable decision');
assert.deepEqual(csv('unit4-data-quality-raw.csv'),model.raw,'Preserve the original observations, including blank, negative and duplicate values');
assert.deepEqual(csv('unit4-data-quality-clean-example.csv'),model.clean.map(row=>row.map(String)));
const cleaned=new Map(model.clean.map(row=>[row[0],row]));
assert.equal(cleaned.size,8);
assert.equal(cleaned.get('E03')[2],8,'Correction uses supplied evidence rather than accepting valid-looking 80');
assert.equal(cleaned.get('E05')[2],3*4,'Convert a verified four-per-pack quantity');
assert.equal(cleaned.get('E06')[2],240,'Keep the supported genuine large value');
assert.equal(cleaned.get('E04')[2],7);
assert.equal(cleaned.get('E04')[4],'2026-10-10','Use the observation date rather than the download date');
assert.equal(cleaned.get('E08')[2],9,'Do not coerce a missing value to zero');
for(const id of ['E09','E10','E11'])assert.equal(cleaned.has(id),false,'Unverified or irrelevant records do not enter the illustrative report');
assert.ok(model.decisions.find(row=>row[0]==='R12')[1].startsWith('Hold'),'Do not silently delete an unverified outlier');
assert.equal(model.raw.find(row=>row[0]==='R12')[3],'120');
assert.equal(model.questions.length,12);
const chapter={id:'unit4-project',sections:[]};
vm.runInNewContext(read('dist/unit4-data-quality.js'),{chapters:[chapter]});
const html=chapter.sections[0][1];
assert.equal((html.match(/<summary>Show explained answer/g)||[]).length,12);
for(const factor of model.factors)assert.ok(html.includes(factor[0]));
assert.match(read('dist/unit4-data-quality.html'),/<main id="main">/);
assert.match(read('dist/unit4-data-quality.html'),/src="unit4-er-print.js"/);
const coverage=JSON.parse(read('dist/unit4-coverage.json'));
assert.equal(coverage.rows.find(row=>row.id==='D15').status,'Draft mapped');
assert.equal(Object.values(coverage.counts).reduce((a,b)=>a+b,0),51);
console.log('Five factors, preserved raw data, evidence-backed corrections, genuine/unverified outliers and worksheet integration passed.');
